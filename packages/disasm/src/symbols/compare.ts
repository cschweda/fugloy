/**
 * The Model I and Model III ROM maps are entered separately, each from its own
 * sources; this compares them address by address (design spec §4.6) so a
 * listing can say which machine it assumed.
 */
import { hex4 } from '@fugloy/z80';
import type { RomClass, TableEntry } from './types.js';

const byKey = (entries: readonly TableEntry[]): Map<number, TableEntry> => new Map(entries.map((e) => [e.key, e]));
const named = (e: TableEntry): string => `${e.name} (${e.kind})`;
/** A table cell: no pipes or line breaks to break the row. */
const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

/** Every address in either table, ascending. */
function addresses(a: ReadonlyMap<number, TableEntry>, b: ReadonlyMap<number, TableEntry>): number[] {
  return [...new Set([...a.keys(), ...b.keys()])].sort((x, y) => x - y);
}

/**
 * Classes each address: `shared` when both tables name it alike (same name and
 * kind), `different` when they disagree, else the one table that has it.
 * `unexplained` has one message per `different` address where neither entry
 * carries a `note` saying why.
 */
export function compareRoms(model1: readonly TableEntry[], model3: readonly TableEntry[]): { classes: Record<string, RomClass>; unexplained: string[] } {
  const one = byKey(model1);
  const three = byKey(model3);
  const classes: Record<string, RomClass> = {};
  const unexplained: string[] = [];
  for (const key of addresses(one, three)) {
    const a = one.get(key);
    const b = three.get(key);
    if (a === undefined) classes[hex4(key)] = 'model3-only';
    else if (b === undefined) classes[hex4(key)] = 'model1-only';
    else if (a.name === b.name && a.kind === b.kind) classes[hex4(key)] = 'shared';
    else {
      classes[hex4(key)] = 'different';
      if (a.note === undefined && b.note === undefined) {
        unexplained.push(`$${hex4(key)} is ${named(a)} in rom-model1.json but ${named(b)} in rom-model3.json, and neither entry has a note saying why`);
      }
    }
  }
  return { classes, unexplained };
}

const CLASSES: readonly RomClass[] = ['shared', 'different', 'model1-only', 'model3-only'];

/** The COMPARISON.md report: a count per class, then every address in either table. */
export function renderComparison(model1: readonly TableEntry[], model3: readonly TableEntry[], classes: Readonly<Record<string, RomClass>>): string {
  const one = byKey(model1);
  const three = byKey(model3);
  const lines = [
    '# Model I and Model III ROMs compared',
    '',
    'Generated by `pnpm symbols` from `rom-model1.json` and `rom-model3.json`. Do not edit.',
    '',
    'Every address in either table. `shared` means both tables give it the same name and kind; `different` means they disagree, and a note on at least one entry says why; `model1-only` and `model3-only` are in one table only.',
    '',
    '| Class | Addresses |',
    '| --- | ---: |',
    ...CLASSES.map((c) => `| ${c} | ${Object.values(classes).filter((x) => x === c).length} |`),
    '',
    '| Address | Class | Model I | Model III | Note |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const key of addresses(one, three)) {
    const a = one.get(key);
    const b = three.get(key);
    const notes = [a?.note === undefined ? '' : `Model I: ${a.note}`, b?.note === undefined ? '' : `Model III: ${b.note}`].filter((n) => n !== '');
    lines.push(
      `| \`$${hex4(key)}\` | ${classes[hex4(key)] ?? ''} | ${a === undefined ? '-' : `\`${cell(a.name)}\` (${a.kind})`} | ${b === undefined ? '-' : `\`${cell(b.name)}\` (${b.kind})`} | ${cell(notes.join('; '))} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

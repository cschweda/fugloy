/**
 * Compiles the cited JSON tables in data/symbols/ into the committed module
 * src/symbols/tables.generated.ts and the Model I/III report COMPARISON.md.
 * Run with `pnpm symbols`; given bad data it prints every problem and exits 1
 * without writing anything. Importing this file has no side effects.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareRoms, renderComparison } from '../src/symbols/compare.js';
import { TABLE_IDS } from '../src/symbols/types.js';
import type { RomClass, Source, TableEntry, TableId } from '../src/symbols/types.js';
import { validateTables } from '../src/symbols/validate.js';

/** A TypeScript string literal for any text: single-quoted (the repo's style), double-quoted when that avoids escaping an apostrophe. */
function q(s: string): string {
  const json = JSON.stringify(s);
  if (s.includes("'") && !s.includes('"')) return json;
  return `'${json.slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
}

/** Addresses as `0x002B`, ports as `0xEC`, service calls in decimal. */
const keyLiteral = (e: TableEntry): string => (e.kind === 'svc' ? String(e.key) : `0x${e.key.toString(16).toUpperCase().padStart(e.kind === 'port' ? 2 : 4, '0')}`);

const sourceLine = (s: Source): string =>
  `  { id: ${q(s.id)}, author: ${q(s.author)}, title: ${q(s.title)}, publisher: ${q(s.publisher)}, year: ${q(s.year)}, ${s.edition === undefined ? '' : `edition: ${q(s.edition)}, `}locator: ${q(s.locator)} },`;

const entryLine = (e: TableEntry): string => {
  const cite = e.cite.map((c) => `{ source: ${q(c.source)}, page: ${q(c.page)} }`).join(', ');
  const note = e.note === undefined ? '' : `, note: ${q(e.note)}`;
  return `    { table: ${q(e.table)}, kind: ${q(e.kind)}, key: ${keyLiteral(e)}, name: ${q(e.name)}, length: ${e.length}, purpose: ${q(e.purpose)}, cite: [${cite}], coined: ${e.coined}${note} },`;
};

/** The generated module: sources, tables (entries by key), and the ROM comparison, as typed literals. */
function renderModule(sources: readonly Source[], tables: Readonly<Record<TableId, readonly TableEntry[]>>, classes: Readonly<Record<string, RomClass>>): string {
  const out = [
    '/* Generated by pnpm symbols from data/symbols/*.json. Do not edit. */',
    "import type { RomComparison, Source, TableEntry, TableId } from './types.js';",
    '',
    '/** The works the tables cite, by id. */',
    'export const SOURCES: readonly Source[] = [',
    ...sources.map(sourceLine),
    '];',
    '',
    "/** Every table's entries, ordered by address, port, or call number. */",
    'export const TABLES: Readonly<Record<TableId, readonly TableEntry[]>> = {',
  ];
  for (const id of TABLE_IDS) {
    const entries = [...tables[id]].sort((a, b) => a.key - b.key);
    if (entries.length === 0) out.push(`  ${q(id)}: [],`);
    else out.push(`  ${q(id)}: [`, ...entries.map(entryLine), '  ],');
  }
  out.push('};', '', '/** How each address in either ROM table compares across the Model I and Model III ROMs. */');
  // Sorted here: JavaScript would enumerate an all-digit key like '1000' ahead of '002B'. Uppercase hex sorts as text the way it does as a number.
  const compared = Object.entries(classes).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  if (compared.length === 0) out.push('export const ROM_COMPARISON: RomComparison = {};');
  else out.push('export const ROM_COMPARISON: RomComparison = {', ...compared.map(([addr, cls]) => `  ${q(addr)}: ${q(cls)},`), '};');
  return `${out.join('\n')}\n`;
}

/**
 * Reads and validates every file in `dataDir`, then renders both outputs. The
 * texts are empty when `errors` is not: a file that is missing or not JSON, a
 * rule the tables break, or a ROM address the two maps name differently
 * without a note. `entries` counts the entries in all tables.
 */
export function buildSymbolOutputs(dataDir: string): { module: string; comparison: string; errors: string[]; entries: number } {
  const errors: string[] = [];
  const read = (file: string): unknown => {
    let text: string;
    try {
      text = readFileSync(join(dataDir, file), 'utf8');
    } catch {
      errors.push(`${file}: cannot read the file`);
      return undefined;
    }
    try {
      return JSON.parse(text) as unknown;
    } catch (e) {
      errors.push(`${file}: not valid JSON (${(e as Error).message})`);
      return undefined;
    }
  };

  const sources = read('sources.json');
  const files = TABLE_IDS.map((id) => ({ file: `${id}.json`, json: read(`${id}.json`) }));
  if (errors.length > 0) return { module: '', comparison: '', errors, entries: 0 };

  const checked = validateTables(files, sources);
  const model1 = checked.tables['rom-model1'];
  const model3 = checked.tables['rom-model3'];
  const { classes, unexplained } = compareRoms(model1, model3);
  errors.push(...checked.errors, ...unexplained);
  if (errors.length > 0) return { module: '', comparison: '', errors, entries: 0 };
  return {
    module: renderModule(checked.sources, checked.tables, classes),
    comparison: renderComparison(model1, model3, classes),
    errors,
    entries: Object.values(checked.tables).reduce((sum, entries) => sum + entries.length, 0),
  };
}

/** True when this file is the program being run, not a module a test imported. */
function runDirectly(): boolean {
  try {
    return process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runDirectly()) {
  const dataDir = fileURLToPath(new URL('../data/symbols/', import.meta.url));
  const modulePath = fileURLToPath(new URL('../src/symbols/tables.generated.ts', import.meta.url));
  const comparisonPath = join(dataDir, 'COMPARISON.md');
  const built = buildSymbolOutputs(dataDir);
  if (built.errors.length > 0) {
    console.error(`pnpm symbols: ${built.errors.length} problem${built.errors.length === 1 ? '' : 's'} in ${dataDir}`);
    for (const error of built.errors) console.error(`  ${error}`);
    process.exit(1);
  }
  writeFileSync(modulePath, built.module);
  writeFileSync(comparisonPath, built.comparison);
  console.log(`wrote ${modulePath} and ${comparisonPath}: ${built.entries} entries in ${TABLE_IDS.length} tables`);
}

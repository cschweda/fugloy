// Converts X.Org font-misc-misc's 6x12.bdf and 6x10.bdf, public domain, into the Run tab's glyph
// table, app/utils/emulator/glyphs.generated.ts (phase 5B Ruling 4). It covers 20H-7EH: 6x12 is
// exactly the Model III's cell (384x192 over 64x16), and 6x10 serves the Model 4's 80x24.
// Nothing comes from a ROM's character generator.
//
// Run once, by hand, on local copies of the two fonts fetched from the pinned commit below:
//
//   curl -fLO https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/<COMMIT>/6x12.bdf
//   curl -fLO https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/<COMMIT>/6x10.bdf
//   pnpm --filter @fugloy/web exec tsx scripts/build-glyphs.ts <dir holding both>
//
// The BDFs are not committed; the table records each one's URL and SHA-256, and the converter
// refuses a font whose header does not say it is public domain.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const COMMIT = 'c4e2af05583764fae3d0b2aa20d5c93b031cbcbf';
export const RAW = `https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/${COMMIT}`;
const FIRST = 0x20;
const LAST = 0x7e;

export interface Cell {
  width: number;
  height: number;
  first: number;
  last: number;
}

/** The font's public-domain statement (its COPYRIGHT property, or a COMMENT line), or null. */
export function publicDomainStatement(text: string): string | null {
  const header = text.slice(0, text.indexOf('STARTCHAR') < 0 ? text.length : text.indexOf('STARTCHAR'));
  for (const line of header.split('\n')) {
    const m = /^(?:COPYRIGHT|COMMENT)\s+"?(.*?)"?\s*$/.exec(line.trim());
    if (m !== null && /public domain/i.test(m[1]!)) return m[1]!;
  }
  return null;
}

/**
 * One byte per pixel row for each character `first..last`, `height` rows each, the leftmost pixel
 * in bit 7. Each glyph sits in its cell from the baseline, FONT_ASCENT rows down, as its BBX says.
 * A character the font lacks is left blank.
 */
export function convertBdf(text: string, cell: Cell): Uint8Array {
  if (publicDomainStatement(text) === null)
    throw new Error('This BDF does not say it is public domain (no COPYRIGHT or COMMENT line saying so), so Fugløy will not use it. Use X.Org font-misc-misc at the pinned commit.');
  const ascentMatch = /^FONT_ASCENT\s+(\d+)/m.exec(text);
  if (ascentMatch === null) throw new Error('This BDF has no FONT_ASCENT, so its glyphs cannot be placed on a baseline.');
  const ascent = Number(ascentMatch[1]);
  const out = new Uint8Array((cell.last - cell.first + 1) * cell.height);
  for (const block of text.split('STARTCHAR').slice(1)) {
    const enc = /^ENCODING\s+(-?\d+)/m.exec(block);
    const code = enc === null ? -1 : Number(enc[1]);
    if (code < cell.first || code > cell.last) continue;
    const bbx = /^BBX\s+(\d+)\s+(\d+)\s+(-?\d+)\s+(-?\d+)/m.exec(block);
    if (bbx === null) throw new Error(`Character ${code} has no BBX line.`);
    const [w, h, xoff, yoff] = bbx.slice(1).map(Number) as [number, number, number, number];
    const bitmap = block.slice(block.indexOf('BITMAP') + 6, block.indexOf('ENDCHAR')).trim().split(/\s+/).filter(Boolean);
    if (bitmap.length !== h) throw new Error(`Character ${code} has ${bitmap.length} bitmap rows; its BBX says ${h}.`);
    if (xoff < 0 || xoff + w > cell.width) throw new Error(`Character ${code} is wider than the ${cell.width}-pixel cell.`);
    const top = ascent - (yoff + h);
    for (let r = 0; r < h; r++) {
      const y = top + r;
      if (y < 0 || y >= cell.height) {
        if (parseInt(bitmap[r]!, 16) !== 0) throw new Error(`Character ${code} reaches outside the ${cell.height}-row cell.`);
        continue;
      }
      // The row's first byte holds the leftmost 8 pixels, MSB first; the cell is at most 8 wide.
      const bits = parseInt(bitmap[r]!.slice(0, 2), 16);
      out[(code - cell.first) * cell.height + y] = (bits >> xoff) & 0xff & ~(0xff >> cell.width);
    }
  }
  return out;
}

const hex = (bytes: Uint8Array): string => Buffer.from(bytes).toString('hex');

/** The generated module's text for the two fonts. */
export function buildTable(input: { file: string; bytes: Uint8Array; cell: Cell; name: string }[]): string {
  const fonts = input.map((f) => ({ ...f, text: Buffer.from(f.bytes).toString('latin1') }));
  const sources = fonts.map((f) => ({
    file: f.file,
    url: `${RAW}/${f.file}`,
    sha256: createHash('sha256').update(f.bytes).digest('hex'),
    statement: publicDomainStatement(f.text)!,
  }));
  const tables = fonts.map((f) => ({ ...f, rows: convertBdf(f.text, f.cell) }));
  const lines = [
    '// Generated by apps/web/scripts/build-glyphs.ts; do not edit. Rebuild it from the fonts below.',
    '//',
    '// The Run tab\'s screen glyphs, 20H-7EH, from X.Org font-misc-misc (the "fixed" fonts), whose',
    '// headers declare them public domain. Nothing here comes from a ROM\'s character generator.',
    ...sources.flatMap((s) => [`//   ${s.file}: ${s.url}`, `//     SHA-256 ${s.sha256}`, `//     "${s.statement}"`]),
    '',
    'const bytes = (hex: string): Uint8Array => Uint8Array.from(hex.match(/../g)!, (b) => parseInt(b, 16));',
    '',
    'export interface GlyphTable {',
    '  readonly width: number;',
    '  readonly height: number;',
    '  readonly first: number;',
    '  readonly last: number;',
    '  /** `height` bytes per character from `first`, one per pixel row, the leftmost pixel in bit 7. */',
    '  readonly rows: Uint8Array;',
    '}',
    '',
    `export const GLYPH_SOURCES = ${JSON.stringify(sources, null, 2)} as const;`,
    '',
    ...tables.flatMap((t) => [
      `export const ${t.name}: GlyphTable = {`,
      `  width: ${t.cell.width},`,
      `  height: ${t.cell.height},`,
      `  first: 0x${t.cell.first.toString(16)},`,
      `  last: 0x${t.cell.last.toString(16)},`,
      `  rows: bytes(`,
      ...(hex(t.rows).match(/.{1,96}/g) ?? []).map((chunk, i, all) => `    '${chunk}'${i < all.length - 1 ? ' +' : ','}`),
      '  ),',
      '};',
      '',
    ]),
  ];
  return lines.join('\n');
}

function main(): void {
  const dir = process.argv[2];
  if (dir === undefined) {
    console.error('usage: tsx scripts/build-glyphs.ts <directory holding 6x12.bdf and 6x10.bdf>');
    process.exit(2);
  }
  const font = (file: string, height: number, name: string) => ({ file, name, bytes: readFileSync(join(dir, file)), cell: { width: 6, height, first: FIRST, last: LAST } });
  const target = fileURLToPath(new URL('../app/utils/emulator/glyphs.generated.ts', import.meta.url));
  writeFileSync(target, buildTable([font('6x12.bdf', 12, 'GLYPHS_6X12'), font('6x10.bdf', 10, 'GLYPHS_6X10')]));
  console.log(`wrote ${target}`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main();

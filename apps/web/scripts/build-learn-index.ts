// Writes the Learn page's index, app/utils/learn/learn-index.generated.ts (phase 6C Task 1, fix round
// 1): for each lesson (content/learn/NN-slug/) and each Space Invaders chapter
// (content/learn/invaders/NN-slug/), what the lists, ◀ ▶, the kicker and the SEO need (slug, number,
// title, idea, models), read from its lesson.md with the lesson format's own parser, so a lesson that
// breaks the format fails here with its sentence. The pages load an item's full text and program on
// their own (utils/learn/lessons), so the first screen carries only this index.
//
//   pnpm --filter @fugloy/web learn-index
//
// Run it after adding a lesson or a chapter, or changing a title, idea or models line; test/learn-format
// fails, naming this command, while the file is not current. Never hand-edit the generated file.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseLesson } from '../app/utils/learn/lesson-format';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CONTENT = join(web, 'content', 'learn');
export const OUT = join(web, 'app', 'utils', 'learn', 'learn-index.generated.ts');

function entries(dir: string): string {
  const rows = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^\d\d-/.test(d.name))
    .map((d) => d.name)
    .sort()
    .map((slug) => {
      const l = parseLesson(slug, readFileSync(join(dir, slug, 'lesson.md'), 'utf8'), readFileSync(join(dir, slug, 'program.z'), 'utf8'));
      return `  { slug: ${JSON.stringify(l.slug)}, number: ${l.number}, title: ${JSON.stringify(l.title)}, idea: ${JSON.stringify(l.idea)}, models: ${JSON.stringify(l.models)} },`;
    });
  return rows.join('\n');
}

/** The generated file's text, from the content as it is now. */
export function learnIndexSource(content = CONTENT): string {
  return [
    '// Generated by scripts/build-learn-index.ts from content/learn: run `pnpm --filter @fugloy/web learn-index`. Never hand-edit.',
    "import type { LessonEntry } from './lesson-format';",
    '',
    '/** Every lesson (content/learn/NN-slug), by number. */',
    'export const LESSON_INDEX: readonly LessonEntry[] = [',
    entries(content),
    '];',
    '',
    '/** Every chapter of Build Space Invaders (content/learn/invaders/NN-slug), by number. */',
    'export const CHAPTER_INDEX: readonly LessonEntry[] = [',
    entries(join(content, 'invaders')),
    '];',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(OUT, learnIndexSource());
  console.log(`Wrote ${OUT}.`);
}
